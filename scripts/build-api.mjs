/**
 * Bundles the production server routes (`src/server/vercel.ts`) into Vercel Functions under `api/`
 * (T3, 2026-11-04). Vercel compiles `api/` itself, but its compiler does not follow this repo's `@/*`
 * alias — the same reason `build-mcp.mjs` exists — so each function is ONE self-contained file.
 * `npm run build:api` writes them; `tests/apiBundle.test.ts` rebuilds them in memory and fails while a
 * checked-in file is stale.
 *
 * Every function answers with the Web `Request → Response` signature Vercel's Node.js runtime takes
 * (`export function GET(request)`); the handlers are the very ones the dev server mounts.
 */
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const BANNER =
  "// GENERATED by scripts/build-api.mjs from src/server/vercel.ts — do not edit.\n" +
  "// Regenerate with `npm run build:api`; tests/apiBundle.test.ts fails while this is stale.";

/** Each function: where it lives under the repo, the route it serves, and the methods it answers. */
export const FUNCTIONS = [
  { file: "api/stocks/[...path].js", route: "stocks", methods: ["GET"] },
  { file: "api/charts/[...path].js", route: "charts", methods: ["GET"] },
  // the list at /api/skills, and each skill at /api/skills/<id>: a catch-all needs a segment
  { file: "api/skills.js", route: "skills", methods: ["GET", "OPTIONS"] },
  { file: "api/skills/[...path].js", route: "skills", methods: ["GET", "OPTIONS"] },
  // the launchpad index, kept in the project's Blob store, and the daily cron that steps it forward
  { file: "api/launchpad/[...path].js", route: "launchpad", methods: ["GET"] },
  { file: "api/cron/index.js", route: "cron", methods: ["GET"] },
];

/** One function's text. */
export async function bundleFunction(fn) {
  const contents =
    `import { get, put } from "@vercel/blob";\n` +
    `import { routes } from "./src/server/vercel";\n` +
    `const blob = { get: (path, options) => get(path, options), put: (path, body, options) => put(path, body, options) };\n` +
    `const handle = routes(process.env, fetch, blob).${fn.route};\n` +
    fn.methods.map((m) => `export function ${m}(request) { return handle(request); }\n`).join("");
  const result = await build({
    stdin: { contents, resolveDir: ROOT, sourcefile: fn.file, loader: "js" },
    bundle: true,
    // installed on Vercel with the project's dependencies, and traced from node_modules there
    external: ["@vercel/blob"],
    format: "esm",
    platform: "node",
    target: "node20",
    write: false,
    legalComments: "none",
    banner: { js: BANNER },
    tsconfig: resolve(ROOT, "tsconfig.json"),
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const fn of FUNCTIONS) {
    const out = resolve(ROOT, fn.file);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, await bundleFunction(fn));
    console.log(`wrote ${fn.file}`);
  }
}
