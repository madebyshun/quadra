// @vitest-environment node
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
// @ts-expect-error — a plain .mjs script with no types; it exports bundleFunction and FUNCTIONS
import { bundleFunction, FUNCTIONS } from "../scripts/build-api.mjs";

/**
 * `api/` holds the production Vercel Functions, GENERATED from `src/server/vercel.ts` (T3). A function
 * nobody regenerates serves yesterday's server — this rebuilds each in memory and compares, byte for byte.
 */
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

describe("the Vercel functions", () => {
  it("are exactly what `npm run build:api` builds from today's source", async () => {
    for (const fn of FUNCTIONS as { file: string }[]) {
      const fresh = (await bundleFunction(fn)) as string;
      expect(readFileSync(resolve(ROOT, fn.file), "utf8") === fresh, `${fn.file} is stale — run \`npm run build:api\``).toBe(true);
      expect(fresh.startsWith("// GENERATED by scripts/build-api.mjs")).toBe(true);
    }
  }, 60_000);

  it("send every page that is not a function to the app, the /api PAGE included", () => {
    const config = JSON.parse(readFileSync(resolve(ROOT, "vercel.json"), "utf8")) as { rewrites: { source: string; destination: string }[] };
    const rule = new RegExp(`^${config.rewrites[0]!.source.replace("/(", "/(")}$`);
    for (const page of ["/", "/docs", "/api", "/verify", "/no-such-page"]) expect(rule.test(page), page).toBe(true);
    for (const fn of ["/api/stocks/base", "/api/skills", "/api/charts/ohlcv"]) expect(rule.test(fn), fn).toBe(false);
  });
});
